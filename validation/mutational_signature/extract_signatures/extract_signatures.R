#!/usr/bin/env Rscript

suppressPackageStartupMessages({
  if (!requireNamespace("optparse", quietly = TRUE))
    install.packages("optparse", repos = "https://cloud.r-project.org")
  library(optparse)
})

opt_list <- list(
  make_option("--matrix", type = "character", default = "r_trinuc_matrix.csv",
              help = "96xN CSV generated by trinucleotideMatrix (write.csv)"),
  make_option("--k", type = "integer", help = "Number of signatures to extract (n)"),
  make_option("--out_prefix", type = "character", default = "signatures",
              help = "Output prefix"),
  make_option("--parallel", type = "integer", default = 4,
              help = "Number of cores for NMF (use 0 to disable parallelism)"),
  make_option("--pconstant", type = "double", default = NA,
              help = "Small positive constant to add if 'non-conformable arrays' error occurs (e.g., 0.01)")
)
opt <- parse_args(OptionParser(option_list = opt_list))
stopifnot(!is.null(opt$k))

ensure_pkg <- function(pkg, bioc = FALSE){
  if (!requireNamespace(pkg, quietly = TRUE)) {
    if (bioc) {
      if (!requireNamespace("BiocManager", quietly = TRUE))
        install.packages("BiocManager", repos = "https://cloud.r-project.org")
      BiocManager::install(pkg, ask = FALSE, update = FALSE)
    } else {
      install.packages(pkg, repos = "https://cloud.r-project.org")
    }
  }
}

ensure_pkg("maftools", bioc = TRUE)
ensure_pkg("NMF", bioc = FALSE)

suppressPackageStartupMessages(library(maftools))

# 1) Read input matrix
M <- as.matrix(read.csv(opt$matrix, row.names = 1, check.names = FALSE))
mode(M) <- "numeric"

# Basic checks
if (any(is.na(M))) stop("The matrix contains NA. Check the CSV.")
if (any(M < 0)) stop("The matrix contains negative values. Check the CSV.")
if (nrow(M) != 96) warning(sprintf("Warning: expected 96 rows (trinucleotides); got %d.", nrow(M)))

sample_totals  <- colSums(M)
context_totals <- rowSums(M)
if (any(sample_totals == 0)) {
  message("- Samples with 0 total mutations detected: ",
          paste(colnames(M)[which(sample_totals == 0)], collapse = ", "))
}
if (any(context_totals == 0)) {
  message("- Contexts with 0 across all samples detected: ",
          paste(rownames(M)[which(context_totals == 0)], collapse = ", "))
}

# 2) Prepare input for maftools::extractSignatures
input_obj <- list(nmf_matrix = t(M))

# 3) Optional parameters
parallel_val <- if (is.null(opt$parallel) || is.na(opt$parallel) || opt$parallel <= 0) NULL else opt$parallel
pconst_val   <- if (is.null(opt$pconstant) || is.na(opt$pconstant)) NULL else opt$pconstant

# If any sample has total 0 and pConstant not set, set it to 0.01
if (is.null(pconst_val) && any(sample_totals == 0)) {
  message("- Applying pConstant=0.01 due to samples with total sum 0.")
  pconst_val <- 0.01
}

# 4) Extract signatures with error handling
run_extract <- function(par_val, pc_val) {
  maftools::extractSignatures(
    mat       = input_obj,
    n         = opt$k,
    parallel  = par_val,
    pConstant = pc_val
  )
}

sig <- tryCatch(
  run_extract(parallel_val, pconst_val),
  error = function(e) {
    message("First attempt failed: ", conditionMessage(e))
    # Retry without parallelism
    pc2 <- if (is.null(pconst_val)) 0.01 else pconst_val
    message("Retrying with pConstant=", pc2, " and without parallelism...")
    run_extract(NULL, pc2)
  }
)

# 5) Save results
S      <- sig$signatures          # 96 x k
E      <- sig$contributions       # k x N
E_abs  <- sig$contributions_abs   # k x N

fn_sig     <- sprintf("%s_signatures_96x%d.csv", opt$out_prefix, ncol(S))
fn_exp     <- sprintf("%s_exposures_%dx%d.csv", opt$out_prefix, nrow(E), ncol(E))
fn_exp_abs <- sprintf("%s_exposures_abs_%dx%d.csv", opt$out_prefix, nrow(E_abs), ncol(E_abs))

write.csv(S,     fn_sig,     quote = TRUE)
write.csv(E,     fn_exp,     quote = TRUE)
write.csv(E_abs, fn_exp_abs, quote = TRUE)

# 6) Summary output
cat("OK
",
    "Signatures: ", fn_sig, "
",
    "Exposures: ", fn_exp, "
",
    "Exposures (abs): ", fn_exp_abs, "
", sep = "")